// Assemble enriched JSON using user_groups.json
const raw = JSON.parse(fs.readFileSync('./data/user_groups.json', 'utf-8'));

// Enrich groups
const enrichedGroups = raw.groups.map(grp => {
  return {
    ...grp,
    stocks: grp.stocks.map(st => {
      const desc = descriptions[st.code] || st.description || "";
      return {
        ...st,
        description: desc
      };
    })
  };
});

// Build categories
const categories = enrichedGroups.map(grp => ({
  id: grp.id,
  name: grp.name
}));

// Build flat stocks
const flatStocks = [];
enrichedGroups.forEach(grp => {
  grp.stocks.forEach((st, idx) => {
    flatStocks.push({
      id: `${grp.id}_${st.code}`,
      code: st.code,
      name: st.name,
      categoryId: grp.id,
      description: st.description,
      createdAt: 1789006151192 + idx
    });
  });
});

const result = {
  groups: enrichedGroups,
  categories: categories,
  stocks: flatStocks,
  exportedAt: new Date().toLocaleString('ja-JP'),
  version: "Simple-X-Web",
  descriptionCount: Object.keys(descriptions).length
};

if (!fs.existsSync('./public')) {
  fs.mkdirSync('./public', { recursive: true });
}
fs.writeFileSync('./public/k-navigator-enriched.json', JSON.stringify(result, null, 2), 'utf-8');
console.log('JSON export successfully written to ./public/k-navigator-enriched.json');
console.log('Enriched stocks count:', flatStocks.length);
